local ast_priorities = {
	[3] = 11, -- not
	[11] = 2, -- and
	[12] = 1, -- or
	[20] = 9, -- `+`
	[21] = 9, -- `-`
	[22] = 10, -- `*`
	[23] = 10, -- `/`
	[24] = 12, -- `^`
	[25] = 5, -- `~`
	[26] = 6, -- `&` bit and
	[27] = 10, -- `%`
	[28] = 3, -- `<`
	[29] = 3, -- `>`
	[30] = 3, -- `==`
	[31] = 3, -- `~=`
	[32] = 8, -- `..`
	[33] = 10, -- `//`
	[34] = 4, -- `|` bit or
	[35] = 7, -- `<<` shl
	[36] = 7, -- `>>` shr
	[38] = 3, -- `<=`
	[39] = 3, -- `>=`
	[50] = 11, -- `-` negation
	[51] = 11, -- `#`
	[52] = 11, -- `~` logical negation
}

